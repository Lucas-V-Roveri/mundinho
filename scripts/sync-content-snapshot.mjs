import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

const configUrl = process.env.MUNDINHO_CONFIG_URL || "https://mundinho-blue.vercel.app/api/config";
const outputPath = resolve(process.env.CONTENT_SNAPSHOT_PATH || "data/content-snapshot.generated.ts");

function assertString(value, label) {
  if (typeof value !== "string" || !value.trim()) throw new Error(`${label} ausente`);
  return value.trim();
}

const configResponse = await fetch(configUrl, { cache: "no-store" });
if (!configResponse.ok) throw new Error(`Falha ao obter runtime config (${configResponse.status})`);
const config = await configResponse.json();
const supabaseUrl = assertString(config.supabaseUrl, "SUPABASE_URL");
const publishableKey = assertString(config.supabasePublishableKey, "SUPABASE_PUBLISHABLE_KEY");
const worldId = assertString(config.worldId, "worldId");
if (worldId !== "mundinho-pra-sempre") throw new Error(`worldId inesperado: ${worldId}`);

const endpoint = `${supabaseUrl}/rest/v1/mundinho_content?select=key,lot,payload&order=lot.asc,key.asc`;
const response = await fetch(endpoint, {
  headers: {
    apikey: publishableKey,
    Authorization: `Bearer ${publishableKey}`,
    Accept: "application/json",
  },
  cache: "no-store",
});
if (!response.ok) throw new Error(`Falha ao exportar mundinho_content (${response.status}): ${await response.text()}`);
const rows = await response.json();
if (!Array.isArray(rows)) throw new Error("mundinho_content não retornou um array");

const guideCount = rows.filter((row) => typeof row?.key === "string" && row.key.startsWith("guide:")).length;
const requiredPages = ["page:progression", "page:amendments", "page:extras", "page:backstage"];
for (const key of requiredPages) {
  if (!rows.some((row) => row?.key === key)) throw new Error(`Snapshot sem ${key}`);
}
if (guideCount !== 35) throw new Error(`Esperados 35 guias, recebidos ${guideCount}`);

const generatedAt = new Date().toISOString();
const body = `/* eslint-disable */\n// AUTO-GENERATED by scripts/sync-content-snapshot.mjs. Do not edit by hand.\nimport type { ContentSnapshotRow } from \"@/types/content\";\n\nexport const CONTENT_SNAPSHOT_GENERATED_AT = ${JSON.stringify(generatedAt)};\nexport const CONTENT_SNAPSHOT_ROWS = ${JSON.stringify(rows, null, 2)} as const satisfies readonly ContentSnapshotRow[];\n`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, body, "utf8");
console.log(`Snapshot gerado: ${rows.length} registros, ${guideCount} guias -> ${outputPath}`);
